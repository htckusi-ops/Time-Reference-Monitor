"""
ptp_config.py – PTP client configuration (multicast / unicast) for the monitor.

The monitor measures a PTP grandmaster with a local ptp4l instance
(ptp4l@<iface>.service, config /etc/linuxptp/ptp4l.conf).  This module owns that
configuration:

* the settings are kept in a small JSON file (survives reboots),
* ptp4l.conf is generated from them (multicast, or unicast negotiation with a
  fixed master IP),
* ptp4l is restarted when the settings change.

The monitor never disciplines the system clock with PTP: with software
timestamping ptp4l is limited to 1 ppb and never steps the clock, so chrony stays
the only source for the system time.  With hardware timestamping ptp4l steers the
PHC only.
"""
from __future__ import annotations

import ipaddress
import json
import os
import re
import subprocess
import threading
from typing import Any, Dict, Optional, Tuple

CONFIG_PATH = "/var/lib/time-reference-monitor/ptp_config.json"
PTP4L_CONF = "/etc/linuxptp/ptp4l.conf"
LEGACY_DOMAIN_PATH = "/var/lib/time-reference-monitor/ptp_domain"

MODES = ("multicast", "unicast")
DELAY_MECHANISMS = ("E2E", "P2P")
TIME_STAMPING = ("auto", "software", "hardware")

# key: (min, max)
_INT_FIELDS: Dict[str, Tuple[int, int]] = {
    "domain": (0, 127),
    "log_announce_interval": (-3, 4),
    "log_sync_interval": (-7, 4),
    "log_min_delay_req_interval": (-7, 4),
    "announce_receipt_timeout": (2, 255),
    "unicast_req_duration": (10, 1000),
    "log_query_interval": (0, 8),
}

DEFAULTS: Dict[str, Any] = {
    "mode": "multicast",
    "domain": 0,
    "master_ip": "",
    "delay_mechanism": "E2E",
    "time_stamping": "auto",
    "log_announce_interval": 0,
    "log_sync_interval": -3,
    "log_min_delay_req_interval": -3,
    "announce_receipt_timeout": 10,
    "unicast_req_duration": 60,
    "log_query_interval": 2,
}

_IFACE_RE = re.compile(r"^[A-Za-z0-9_.:-]{1,15}$")


def validate(raw: Dict[str, Any], base: Optional[Dict[str, Any]] = None) -> Tuple[Dict[str, Any], Optional[str]]:
    """Merge *raw* over *base* (or defaults) and validate. Returns (config, error)."""
    cfg = dict(base or DEFAULTS)
    for k, v in (raw or {}).items():
        if k in DEFAULTS:
            cfg[k] = v

    if cfg["mode"] not in MODES:
        return cfg, "Modus muss 'multicast' oder 'unicast' sein."
    if cfg["time_stamping"] not in TIME_STAMPING:
        return cfg, "Timestamping muss auto, software oder hardware sein."

    for key, (lo, hi) in _INT_FIELDS.items():
        try:
            cfg[key] = int(cfg[key])
        except (TypeError, ValueError):
            return cfg, f"Ungültiger Wert für {key}."
        if not lo <= cfg[key] <= hi:
            return cfg, f"{key} muss zwischen {lo} und {hi} liegen."

    if cfg["mode"] == "unicast":
        cfg["delay_mechanism"] = "E2E"   # unicast negotiation is E2E only
        ip = str(cfg.get("master_ip") or "").strip()
        try:
            addr = ipaddress.ip_address(ip)
        except ValueError:
            return cfg, "Unicast braucht eine gültige Master-IPv4-Adresse."
        if addr.version != 4 or addr.is_multicast or addr.is_unspecified:
            return cfg, "Master-IP muss eine Unicast-IPv4-Adresse sein."
        cfg["master_ip"] = str(addr)
    else:
        cfg["master_ip"] = str(cfg.get("master_ip") or "").strip()
        if cfg["delay_mechanism"] not in DELAY_MECHANISMS:
            return cfg, "Delay-Mechanismus muss E2E oder P2P sein."
    return cfg, None


def detect_hw_timestamping(iface: str) -> bool:
    """True if the NIC offers hardware transmit timestamping and a PHC."""
    if not _IFACE_RE.match(iface):
        return False
    try:
        out = subprocess.run(["ethtool", "-T", iface], capture_output=True, text=True, timeout=5).stdout
    except Exception:
        return False
    m = re.search(r"PTP Hardware Clock:\s*(\d+)", out)
    return "hardware-transmit" in out and m is not None


def render_conf(cfg: Dict[str, Any], iface: str, hw_timestamping: Optional[bool] = None) -> str:
    """Return the text of ptp4l.conf for *cfg*."""
    if hw_timestamping is None:
        hw_timestamping = (cfg["time_stamping"] == "hardware") or (
            cfg["time_stamping"] == "auto" and detect_hw_timestamping(iface))
    elif cfg["time_stamping"] != "auto":
        hw_timestamping = cfg["time_stamping"] == "hardware"

    unicast = cfg["mode"] == "unicast"
    L = [
        "# /etc/linuxptp/ptp4l.conf",
        "# Generated by Time Reference Monitor (ptp_config.py) – edit via Settings page.",
        "",
        "[global]",
        "# Monitoring client: never becomes master (priority 255 loses every BMCA)",
        "slaveOnly                   1",
        "priority1                   255",
        "priority2                   255",
        "clockClass                  255",
        "clockAccuracy               0xFE",
        "offsetScaledLogVariance     0xFFFF",
        "timeSource                  0xA0",
        "",
        f"domainNumber                {cfg['domain']}",
        "network_transport           UDPv4",
        f"delay_mechanism             {cfg['delay_mechanism']}",
        f"logAnnounceInterval         {cfg['log_announce_interval']}",
        f"logSyncInterval             {cfg['log_sync_interval']}",
        f"logMinDelayReqInterval      {cfg['log_min_delay_req_interval']}",
        f"announceReceiptTimeout      {cfg['announce_receipt_timeout']}",
        "",
        "uds_address                 /var/run/ptp4l",
        "uds_ro_address              /var/run/ptp4lro",
        "",
    ]
    if hw_timestamping:
        L += ["time_stamping               hardware", "hwts_filter                 full",
              "# ptp4l steers the PHC only; the system clock stays with chrony.", ""]
    else:
        L += ["time_stamping               software",
              "# Measure only: the servo may not move the system clock (chrony owns it).",
              "max_frequency               1",
              "first_step_threshold        0",
              "step_threshold              0", ""]
    if unicast:
        L += [f"unicast_req_duration        {cfg['unicast_req_duration']}", "",
              "[unicast_master_table]", "table_id                    1",
              f"logQueryInterval            {cfg['log_query_interval']}",
              f"UDPv4                       {cfg['master_ip']}", "",
              f"[{iface}]", "unicast_master_table        1", ""]
    return "\n".join(L)


def _run_sudo(args, input_text: Optional[str] = None, timeout: float = 20.0) -> Tuple[bool, str]:
    try:
        p = subprocess.run(["sudo", "-n"] + args, input=input_text, capture_output=True,
                           text=True, timeout=timeout)
    except Exception as exc:  # noqa: BLE001
        return False, str(exc)
    return p.returncode == 0, (p.stderr or p.stdout or "").strip()


class PtpConfigStore:
    """Thread-safe holder of the PTP settings; applies them to ptp4l."""

    def __init__(self, iface: str, default_domain: int = 0, path: str = CONFIG_PATH,
                 system_changes: bool = True) -> None:
        self._lock = threading.Lock()
        self._path = path
        self.iface = iface
        self._system_changes = system_changes
        base = dict(DEFAULTS)
        base["domain"] = int(default_domain)
        try:  # migrate the domain saved by older versions (plain-number file)
            with open(LEGACY_DOMAIN_PATH) as f:
                base["domain"] = int(f.read().strip())
        except (OSError, ValueError):
            pass
        self._cfg = base
        try:
            with open(path) as f:
                cfg, err = validate(json.load(f), base)
            if err is None:
                self._cfg = cfg
        except (OSError, ValueError):
            pass

    def get(self) -> Dict[str, Any]:
        with self._lock:
            return dict(self._cfg)

    def domain(self) -> int:
        with self._lock:
            return int(self._cfg["domain"])

    def update(self, changes: Dict[str, Any]) -> Tuple[bool, str, Dict[str, Any]]:
        """Validate, persist, write ptp4l.conf and restart ptp4l."""
        with self._lock:
            cfg, err = validate(changes, self._cfg)
            if err:
                return False, err, dict(self._cfg)
            if not self._system_changes:
                self._cfg = cfg
                return True, "Gespeichert (Mock-Modus: ptp4l nicht verändert).", dict(cfg)
            if not _IFACE_RE.match(self.iface):
                return False, "Ungültiger Interface-Name.", dict(self._cfg)

            text = render_conf(cfg, self.iface)
            ok, msg = _run_sudo(["/usr/bin/tee", PTP4L_CONF], input_text=text)
            if not ok:
                return False, f"ptp4l.conf konnte nicht geschrieben werden: {msg}", dict(self._cfg)
            try:
                os.makedirs(os.path.dirname(self._path), exist_ok=True)
                tmp = self._path + ".tmp"
                with open(tmp, "w") as f:
                    json.dump(cfg, f, indent=2)
                os.replace(tmp, self._path)
            except OSError as exc:
                return False, f"Einstellungen konnten nicht gespeichert werden: {exc}", dict(self._cfg)
            self._cfg = cfg
            ok, msg = _run_sudo(["/bin/systemctl", "restart", f"ptp4l@{self.iface}.service"])
            if not ok:
                return False, f"Gespeichert, aber ptp4l-Neustart fehlgeschlagen: {msg}", dict(cfg)
            return True, "Gespeichert, ptp4l neu gestartet.", dict(cfg)


def _main(argv=None) -> int:
    """CLI used by setup.sh/update.sh:  python3 ptp_config.py render --iface eth0"""
    import argparse
    ap = argparse.ArgumentParser(description="Render ptp4l.conf from the stored PTP settings")
    ap.add_argument("command", choices=["render"])
    ap.add_argument("--iface", default="eth0")
    ap.add_argument("--domain", type=int, default=0, help="default domain if no config is stored")
    args = ap.parse_args(argv)
    if not _IFACE_RE.match(args.iface):
        ap.error("invalid interface name")
    store = PtpConfigStore(iface=args.iface, default_domain=args.domain, system_changes=False)
    cfg = store.get()
    if cfg["mode"] == "unicast" and not cfg["master_ip"]:
        cfg["mode"] = "multicast"
    print(render_conf(cfg, args.iface), end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(_main())
